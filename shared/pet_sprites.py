# pet_sprites.py - the creatures, as ASCII art, packed for Display.icon()
#
# Part of the unofficial COLDCARD Tamagotchi fork. See NOTICE and LICENSE-PET.
#
# '#' is a lit pixel, anything else is off. Each sprite becomes a tuple
# (w, h, w_bytes, 0, data) in MONO_HLSB, exactly like graphics_mk4.py, so
# dis.icon(x, y, SPRITE) draws it with off-pixels transparent.
#
# Bodies have a blank face; eyes and mouth are blitted on top at anchors, so
# one body serves every mood and three eye styles. Genome picks body & eyes.
#

def pack(art):
    rows = [ln for ln in art.split('\n') if ln.strip('\r')]
    # drop common leading indentation
    ind = min(len(ln) - len(ln.lstrip(' ')) for ln in rows)
    rows = [ln[ind:].rstrip('\r') for ln in rows]
    w = max(len(r) for r in rows)
    h = len(rows)
    bw = (w + 7) // 8
    out = bytearray(bw * h)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == '#':
                out[y * bw + (x >> 3)] |= 0x80 >> (x & 7)
    return (w, h, bw, 0, bytes(out))


class Body:
    # sprite + where the face goes (relative to sprite's top-left)
    def __init__(self, art, face_x, face_y, mouth_dx=2, mouth_dy=5):
        self.spr = pack(art)
        self.w, self.h = self.spr[0], self.spr[1]
        self.fx, self.fy = face_x, face_y          # eyes anchor
        self.mx, self.my = face_x + mouth_dx, face_y + mouth_dy   # mouth anchor


